def create_embedding(
    text,
    task_type="RETRIEVAL_DOCUMENT"
):

    response = client.models.embed_content(
        model=EMBEDDING_MODEL,
        contents=text,
        config=types.EmbedContentConfig(
            task_type=task_type,
            output_dimensionality=768
        )
    )

    return np.array(
        response.embeddings[0].values,
        dtype=np.float32
    )

